-- Login sessions (spec 001). These are the tables of Spring Session JDBC, with the names and columns it expects.
-- Wardroom creates them here; Spring Session does not create them itself. The times are milliseconds since 1970,
-- which need BIGINT so that the generated database classes use 64-bit numbers.
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID            TEXT    NOT NULL PRIMARY KEY,
    SESSION_ID            TEXT    NOT NULL,
    CREATION_TIME         BIGINT  NOT NULL,
    LAST_ACCESS_TIME      BIGINT  NOT NULL,
    MAX_INACTIVE_INTERVAL INTEGER NOT NULL,
    EXPIRY_TIME           BIGINT  NOT NULL,
    PRINCIPAL_NAME        TEXT
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID TEXT NOT NULL REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE,
    ATTRIBUTE_NAME     TEXT NOT NULL,
    ATTRIBUTE_BYTES    BLOB NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME)
);
